// The meal library: real meals with ingredients, seasonings and steps.
// The planner picks from these first and only falls back to building a meal from parts when nothing fits.
//
// Each ingredient is [foodId, grams for a ~450–550 kcal serving, flags]:
//   P   this ingredient is scaled to hit the meal's protein target
//   C   scaled to hit the carb target
//   F   scaled to fill the remaining calories
//   ?   optional: dropped (not a deal-breaker) when the person's diet doesn't allow it,
//       on very-low-carb diets for carb ingredients, or when someone marked it "won't eat"
// Ingredients without P/C/F stay at the listed amount. Seasonings carry no meaningful calories.
//
// Design rules every meal follows (fat loss while keeping muscle):
//   - a solid protein source in every meal and snack
//   - vegetables or fruit in nearly every meal, for fiber and volume
//   - whole grains, beans or potatoes as the carb, with healthy fats in measured amounts
//   - cooking methods that don't add hidden fat (bake, grill, air-fry, sauté in a measured amount of oil)

